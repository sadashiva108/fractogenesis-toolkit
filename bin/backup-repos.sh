#!/usr/bin/env bash
# =============================================================================
# backup-repos.sh
#
# Phase 2A repo backup entrypoint: refreshes the repo audit and gitignore
# superset reports, then (once reviewed) stages ignored/gitignored files for
# backup before a reimage.
#
# --- BEGIN USAGE ---
# Usage:
#   cd <repo-root>
#   chmod +x bin/backup-repos.sh
#
#   # Default -- refresh repo audit + gitignore superset outputs
#   ./bin/backup-repos.sh
#
#   # Broad ignored-file dry run / copy (everything Git reports as ignored)
#   ./bin/backup-repos.sh --direct-ignored-dry-run
#   ./bin/backup-repos.sh --direct-ignored-copy
#
#   # Reviewed selected-pattern flow (recommended -- see gitignore-review-template.txt)
#   ./bin/backup-repos.sh --selected-dry-run
#   ./bin/backup-repos.sh --selected-filtered-dry-run
#   ./bin/backup-repos.sh --selected-copy
#
#   # Override artifact root or Git roots
#   ./bin/backup-repos.sh --artifact-root /path/to/reimage-artifact-root
#   ./bin/backup-repos.sh --root /path/to/work-repositories --root /path/to/personal-repositories
#
#   # Open primary output after the run
#   ./bin/backup-repos.sh --open
#
# Modes:
#   (default)                     Refresh the repo audit and gitignore superset outputs.
#   --direct-ignored-dry-run      Run the broad ignored-file dry run.
#   --direct-ignored-copy         Run the broad ignored-file copy.
#   --selected-dry-run            Run the reviewed selected-pattern dry run.
#   --selected-filtered-dry-run   Run the reviewed selected-pattern dry run with exclude list.
#   --selected-copy               Run the reviewed selected-pattern final copy.
#   --stale-ignore-scan           Report .gitignore entries naming one literal file
#                                 that no longer matches anything on disk.
#
# Options:
#   --artifact-root PATH   Override REIMAGE_ARTIFACT_ROOT from reimage.env.
#   --root DIR              Override Git roots from reimage.env. Repeatable.
#   --include-heavy         Only valid with direct ignored-file modes.
#   --preserve-selections   Default mode only: carry forward [x] marks in
#                            gitignore-review-template.txt instead of resetting them.
#   --status-interval SEC   Print a still-running update every SEC seconds. Default: 10.
#   --no-status             Disable periodic still-running updates.
#   --open                  Open the primary output after the run.
#   -h, --help              Show this message and exit.
#
# Files:
#   All reads and writes are under REIMAGE_ARTIFACT_ROOT (the per-run drive),
#   with one exception noted below. Nothing is ever written to
#   REIMAGE_WORKSPACE_ROOT.
#
#   Read-only inputs you maintain (this script never writes or overwrites them):
#     gitignore-superset/backup-exclude-list.txt
#         Exclude list required by --selected-filtered-dry-run and --selected-copy.
#     gitignore-superset/secrets-patterns.txt
#         Optional; when present, diverts secret-shaped candidates in selected modes.
#     REIMAGE_ARTIFACT_ROOT/gitignore-superset/gitignore-review-template.direct-nonsecret-recommended.txt
#         The one workspace read: read-only, drives the selected-nonsecret ignored
#         -file feed. Lives with your curated config, like the artifact-config
#         fragments; never written.
#
#   Read AND regenerated by the default refresh:
#     gitignore-superset/gitignore-review-template.txt
#         The [x] review template. Selected-* modes READ it; the default refresh
#         REWRITES it (see Re-run behavior).
#
#   Written / regenerated by the default refresh (previous contents replaced):
#     repo-audit-reports/         Repo audit runs, MANIFEST.md, repo-audit-index.md,
#                                 and official/<context>.txt.
#     gitignore-superset/         Superset inventories and pattern reports.
#     gitignore-superset/gitignore-review/
#                                 Ignored-candidate feeds consumed later by the
#                                 Phase 3C cert/Keychain plan.
#
#   Written only by the staging modes (not the default refresh):
#     staged-ignored-files/dryrun/           --selected-dry-run, --direct-ignored-dry-run.
#     staged-ignored-files/dryrun-filtered/  --selected-filtered-dry-run.
#     staged-ignored-files/live/             --selected-copy, --direct-ignored-copy.
#
# Re-run behavior:
#   Re-running the default refresh REGENERATES and overwrites the superset
#   reports, the ignored-candidate feeds, and gitignore-review-template.txt. The
#   template is reset to all [ ] -- discarding your [x] marks -- UNLESS you pass
#   --preserve-selections, which carries checked patterns forward. The exclude
#   list, secrets-patterns list, and direct-nonsecret template are inputs you
#   maintain and are never overwritten.
#
# Configuration precedence:
#   1. Explicit command-line options for this invocation.
#   2. Environment values already exported by the caller or optional .envrc.
#   3. Values loaded from reimage.env.
#   4. Defaults and reusable fragments loaded by artifact-config.sh.
#
# Exit status:
#   0  Run completed successfully.
#   1  Run started but a workflow step failed (a helper returned nonzero, or a
#      required input file was missing when the selected mode needed it).
#   2  Usage, configuration, prerequisite, or dependency error.
# --- END USAGE ---
# =============================================================================

set -euo pipefail

# ── Load shared reimage config ────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# This script lives at <repo>/bin/backup-repos.sh, so .internal/ is a
# sibling of bin/, one level up from this script's own directory.
CONFIG_LOADER="$(dirname "$SCRIPT_DIR")/.internal/load-reimage-config.sh"
if [[ ! -f "$CONFIG_LOADER" ]]; then
  echo "ERROR: shared config loader not found: $CONFIG_LOADER" >&2
  exit 2
fi
# shellcheck source=../.internal/load-reimage-config.sh
source "$CONFIG_LOADER"

# The repository audit is a run category like any other. This reads its official
# pointer rather than the `latest-run.txt` it used to write, so the lineage being
# asked for is named rather than inferred from whichever run happened to be last.
RUNS_LIB="$REPO_ROOT/.internal/artifact-runs.sh"
if [[ ! -f "$RUNS_LIB" ]]; then
  echo "ERROR: shared run index not found: $RUNS_LIB" >&2
  exit 2
fi
# shellcheck source=../.internal/artifact-runs.sh
source "$RUNS_LIB"
# ─────────────────────────────────────────────────────────────────────────────

usage() {
  sed -n '/^# --- BEGIN USAGE ---$/,/^# --- END USAGE ---$/p' "$0" \
    | sed '1d;$d;s/^# //;s/^#$//'
}

require_option_value() {
  local option="$1"
  local value="${2:-}"

  if [[ -z "$value" || "$value" == --* ]]; then
    echo "ERROR: $option requires a non-empty value." >&2
    usage >&2
    exit 2
  fi
}

OPEN_AFTER=false
INCLUDE_HEAVY=false
PRESERVE_SELECTIONS=false
STATUS_ENABLED=true
STATUS_INTERVAL=10
MODE="default"
MODE_SET_COUNT=0
ROOTS=()

while [[ $# -gt 0 ]]; do
  case "$1" in
    --artifact-root)
      require_option_value "$1" "${2:-}"
      REIMAGE_ARTIFACT_ROOT="$2"
      shift 2
      ;;
    --root)
      require_option_value "$1" "${2:-}"
      ROOTS+=("$2")
      shift 2
      ;;
    --direct-ignored-dry-run) MODE="direct-ignored-dry-run"; MODE_SET_COUNT=$((MODE_SET_COUNT + 1)); shift ;;
    --direct-ignored-copy) MODE="direct-ignored-copy"; MODE_SET_COUNT=$((MODE_SET_COUNT + 1)); shift ;;
    --selected-dry-run) MODE="selected-dry-run"; MODE_SET_COUNT=$((MODE_SET_COUNT + 1)); shift ;;
    --selected-filtered-dry-run) MODE="selected-filtered-dry-run"; MODE_SET_COUNT=$((MODE_SET_COUNT + 1)); shift ;;
    --selected-copy) MODE="selected-copy"; MODE_SET_COUNT=$((MODE_SET_COUNT + 1)); shift ;;
    --stale-ignore-scan) MODE="stale-ignore-scan"; MODE_SET_COUNT=$((MODE_SET_COUNT + 1)); shift ;;
    --include-heavy) INCLUDE_HEAVY=true; shift ;;
    --preserve-selections) PRESERVE_SELECTIONS=true; shift ;;
    --status-interval)
      require_option_value "$1" "${2:-}"
      if [[ "$2" != *[!0-9]* && -n "$2" ]]; then
        STATUS_INTERVAL="$2"
      else
        echo "ERROR: --status-interval requires a positive integer, got: $2" >&2
        usage >&2
        exit 2
      fi
      shift 2
      ;;
    --no-status) STATUS_ENABLED=false; shift ;;
    --open) OPEN_AFTER=true; shift ;;
    -h|--help) usage; exit 0 ;;
    *)
      echo "ERROR: unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

if [[ "$MODE_SET_COUNT" -gt 1 ]]; then
  echo "ERROR: choose only one mode flag per run." >&2
  exit 1
fi

case "$STATUS_INTERVAL" in
  ''|*[!0-9]*|0)
    echo "ERROR: --status-interval must be a positive integer." >&2
    exit 2
    ;;
esac

if [[ -z "${REIMAGE_ARTIFACT_ROOT:-}" ]]; then
  echo "ERROR: REIMAGE_ARTIFACT_ROOT is not set. Source reimage.env or pass --artifact-root PATH." >&2
  exit 1
fi

if [[ ! -d "$REIMAGE_ARTIFACT_ROOT" ]]; then
  echo "ERROR: artifact root not found: $REIMAGE_ARTIFACT_ROOT" >&2
  exit 1
fi

if [[ ${#ROOTS[@]} -eq 0 ]]; then
  if [[ -n "${GIT_WORK_REPO_ROOT:-}" && -d "${GIT_WORK_REPO_ROOT:-}" ]]; then
    ROOTS+=("$GIT_WORK_REPO_ROOT")
  fi
  if [[ -n "${GIT_PERSONAL_REPO_ROOT:-}" && -d "${GIT_PERSONAL_REPO_ROOT:-}" ]]; then
    ROOTS+=("$GIT_PERSONAL_REPO_ROOT")
  fi
fi


# stale-ignore-scan reads the pattern/source map written by an earlier refresh
# and never walks a repository, so it does not need the roots.
if [[ ${#ROOTS[@]} -eq 0 && "$MODE" != "stale-ignore-scan" ]]; then
  echo "ERROR: No Git repository roots found." >&2
  echo "Set GIT_WORK_REPO_ROOT and/or GIT_PERSONAL_REPO_ROOT in reimage.env, or pass --root <dir>." >&2
  exit 2
fi

for root in "${ROOTS[@]}"; do
  if [[ ! -d "$root" ]]; then
    echo "ERROR: Git root does not exist: $root" >&2
    exit 1
  fi
done

if [[ "$INCLUDE_HEAVY" == true && "$MODE" != "direct-ignored-dry-run" && "$MODE" != "direct-ignored-copy" ]]; then
  echo "ERROR: --include-heavy is only valid with direct ignored-file modes." >&2
  exit 1
fi

if [[ "$PRESERVE_SELECTIONS" == true && "$MODE" != "default" ]]; then
  echo "ERROR: --preserve-selections only applies to the default refresh mode." >&2
  exit 1
fi

# The top-level containers below are assumed to already exist, created by
# prepare-artifact-root.md's standard artifact-root layout -- this script
# does not create them itself, see the "Prerequisites" section of
# backup-repos.md. dryrun/, dryrun-filtered/, and live/ under
# staged-ignored-files/ are different: those are child directories owned by
# this runbook's own helper scripts, not by prepare-artifact-root.md, so
# they're created below instead of checked as a prerequisite.
REPO_AUDIT_DIR="$REIMAGE_ARTIFACT_ROOT/repo-audit-reports"
GITIGNORE_DIR="$REIMAGE_ARTIFACT_ROOT/gitignore-superset"
STAGED_IGNORED_DIR="$REIMAGE_ARTIFACT_ROOT/staged-ignored-files"
SELECTED_DRYRUN_DIR="$STAGED_IGNORED_DIR/dryrun"
SELECTED_FILTERED_DRYRUN_DIR="$STAGED_IGNORED_DIR/dryrun-filtered"
SELECTED_FINAL_DIR="$STAGED_IGNORED_DIR/live"
MANIFEST_PATH="$REPO_AUDIT_DIR/MANIFEST.md"

for dir in \
  "$REPO_AUDIT_DIR" \
  "$GITIGNORE_DIR" \
  "$STAGED_IGNORED_DIR"; do
  if [[ ! -d "$dir" ]]; then
    echo "ERROR: expected artifact directory not found: $dir" >&2
    echo "This directory should already exist as part of the standard artifact-root" >&2
    echo "layout created by prepare-artifact-root.md. Run that runbook first, or confirm" >&2
    echo "REIMAGE_ARTIFACT_ROOT points at the right location." >&2
    exit 2
  fi
done

mkdir -p "$SELECTED_DRYRUN_DIR" "$SELECTED_FILTERED_DRYRUN_DIR" "$SELECTED_FINAL_DIR"

# This script lives at <repo>/bin/backup-repos.sh; helpers live alongside
# the shared config loader under <repo>/.internal/git/.
HELPERS_DIR="$(dirname "$SCRIPT_DIR")/.internal/git"
AUDIT_HELPER="$HELPERS_DIR/capture-repo-audit.sh"
DIRECT_IGNORED_HELPER="$HELPERS_DIR/stage-ignored-files.sh"
SUPERSET_HELPER="$HELPERS_DIR/collect-gitignore-superset.sh"
SELECTED_HELPER="$HELPERS_DIR/stage-selected-patterns.py"
IGNORED_SCAN_HELPER="$HELPERS_DIR/scan-gitignored-candidates.py"
STALE_IGNORE_HELPER="$HELPERS_DIR/scan-stale-ignore-entries.py"

for helper in "$AUDIT_HELPER" "$DIRECT_IGNORED_HELPER" "$SUPERSET_HELPER" "$SELECTED_HELPER" "$IGNORED_SCAN_HELPER"; do
  if [[ ! -f "$helper" ]]; then
    echo "ERROR: helper not found: $helper" >&2
    exit 2
  fi
done

HELPER_ROOT_ARGS=()
for root in "${ROOTS[@]}"; do
  HELPER_ROOT_ARGS+=(--root "$root")
done

TEMPLATE_PATH="$GITIGNORE_DIR/gitignore-review-template.txt"
EXCLUDE_LIST_PATH="$GITIGNORE_DIR/backup-exclude-list.txt"
SECRETS_PATTERNS_PATH="$GITIGNORE_DIR/secrets-patterns.txt"
# The direct-nonsecret template is a read-only curated input that lives in the
# workspace (like artifact-config fragments); this workflow never writes it.
NONSECRET_TEMPLATE_PATH="$GITIGNORE_DIR/gitignore-review-template.direct-nonsecret-recommended.txt"
# Ignored-candidate review feeds are generated per-run and stay on the artifact
# drive (consumed later by the Phase 3C cert/Keychain plan).
IGNORED_REVIEW_DIR="$GITIGNORE_DIR/gitignore-review"
LATEST_AUDIT_REPORT=""
OPEN_TARGET=""
MODE_SUMMARY=""
ACTIVE_CHILD_PID=""

stop_active_child() {
  if [[ -n "$ACTIVE_CHILD_PID" ]] && kill -0 "$ACTIVE_CHILD_PID" 2>/dev/null; then
    kill "$ACTIVE_CHILD_PID" 2>/dev/null || true
    wait "$ACTIVE_CHILD_PID" 2>/dev/null || true
  fi
}

trap 'stop_active_child; exit 130' INT TERM

run_with_status() {
  local label="$1"
  shift

  local started now elapsed next_update rc
  printf '\n==> %s\n' "$label"
  printf '    Started: %s\n' "$(date '+%Y-%m-%d %H:%M:%S')"

  "$@" &
  ACTIVE_CHILD_PID=$!
  started="$(date +%s)"
  next_update="$STATUS_INTERVAL"

  while kill -0 "$ACTIVE_CHILD_PID" 2>/dev/null; do
    sleep 1
    if [[ "$STATUS_ENABLED" == true ]] && kill -0 "$ACTIVE_CHILD_PID" 2>/dev/null; then
      now="$(date +%s)"
      elapsed=$((now - started))
      if (( elapsed >= next_update )); then
        printf '    [%s] Still running: %s (%ds elapsed)\n' "$(date '+%H:%M:%S')" "$label" "$elapsed"
        next_update=$((next_update + STATUS_INTERVAL))
      fi
    fi
  done

  if wait "$ACTIVE_CHILD_PID"; then
    rc=0
  else
    rc=$?
  fi
  ACTIVE_CHILD_PID=""

  now="$(date +%s)"
  elapsed=$((now - started))
  if [[ "$rc" -eq 0 ]]; then
    printf '    Completed: %s (%ds)\n' "$label" "$elapsed"
  else
    printf '    FAILED: %s (exit %d after %ds)\n' "$label" "$rc" "$elapsed" >&2
  fi
  return "$rc"
}

resolve_latest_audit_report() {
  local latest_run_relative=""
  local latest_report=""

  latest_run_relative="$(artifact_run_official "$REPO_AUDIT_DIR" "pre-image" 2>/dev/null || true)"
  if [[ -z "$latest_run_relative" ]]; then
    echo "ERROR: no official pre-image repository-audit run under: $REPO_AUDIT_DIR" >&2
    return 1
  fi

  case "$latest_run_relative" in
    runs/pre-image-*) ;;
    *)
      echo "ERROR: invalid official repository-audit run pointer: ${latest_run_relative:-<empty>}" >&2
      return 1
      ;;
  esac

  case "$latest_run_relative" in
    *..*|/*)
      echo "ERROR: unsafe latest repository-audit run pointer: $latest_run_relative" >&2
      return 1
      ;;
  esac

  latest_report="$REPO_AUDIT_DIR/$latest_run_relative/repo-audit-summary.txt"
  if [[ ! -f "$latest_report" ]]; then
    echo "ERROR: latest repository-audit report not found: $latest_report" >&2
    return 1
  fi

  printf '%s\n' "$latest_report"
}

run_default_refresh() {
  run_with_status "Repository audit" \
    bash "$AUDIT_HELPER" "${HELPER_ROOT_ARGS[@]}" --dest "$REPO_AUDIT_DIR" --context pre-image
  LATEST_AUDIT_REPORT="$(resolve_latest_audit_report)"
  local superset_args=(--dest "$GITIGNORE_DIR" --include-git-excludes --include-global-excludes)
  if [[ "$PRESERVE_SELECTIONS" == true ]]; then
    superset_args+=(--preserve-selections)
  fi
  run_with_status "Gitignore superset scan" \
    bash "$SUPERSET_HELPER" "${HELPER_ROOT_ARGS[@]}" "${superset_args[@]}"
  mkdir -p "$IGNORED_REVIEW_DIR"
  local nonsecret_args=()
  if [[ -f "$NONSECRET_TEMPLATE_PATH" ]]; then
    nonsecret_args=(--nonsecret-template "$NONSECRET_TEMPLATE_PATH")
  fi
  run_with_status "Gitignore ignored-candidate scan" \
    python3 "$IGNORED_SCAN_HELPER" "${HELPER_ROOT_ARGS[@]}" --out-dir "$IGNORED_REVIEW_DIR" "${nonsecret_args[@]}"
  OPEN_TARGET="$LATEST_AUDIT_REPORT"
  MODE_SUMMARY="Refreshed repo audit, gitignore superset, and ignored-candidate feeds"
}

run_direct_ignored() {
  local dest="$1"
  shift
  run_with_status "Broad ignored-file scan" \
    bash "$DIRECT_IGNORED_HELPER" "${HELPER_ROOT_ARGS[@]}" --dest "$dest" "$@"
  OPEN_TARGET="$dest"
}

run_selected() {
  local dest="$1"
  shift
  if [[ ! -f "$TEMPLATE_PATH" ]]; then
    echo "ERROR: include template not found: $TEMPLATE_PATH" >&2
    echo "Run backup-repos.sh with no mode first to refresh the gitignore superset." >&2
    exit 2
  fi
  # secrets-patterns.txt is opt-in: if present, route credential-shaped
  # candidates into secrets-encrypted/repos-gitignored/ so the Phase 3C DMG
  # sweeps them, instead of leaving them in a holding tree the DMG never reads.
  # Its absence is not an error -- unlike EXCLUDE_LIST_PATH below, this
  # capability works whether or not the file has been created yet.
  local secrets_args=()
  if [[ -f "$SECRETS_PATTERNS_PATH" ]]; then
    secrets_args=(--secrets-patterns "$SECRETS_PATTERNS_PATH" \
                  --secrets-dest "$REIMAGE_ARTIFACT_ROOT/secrets-encrypted/repos-gitignored")
  fi
  run_with_status "Selected-pattern staging scan" \
    python3 "$SELECTED_HELPER" --include-template "$TEMPLATE_PATH" "${HELPER_ROOT_ARGS[@]}" --dest "$dest" "${secrets_args[@]}" "$@"
  OPEN_TARGET="$dest"
}

case "$MODE" in
  default)
    run_default_refresh
    ;;
  direct-ignored-dry-run)
    if [[ "$INCLUDE_HEAVY" == true ]]; then
      run_direct_ignored "$SELECTED_DRYRUN_DIR" --include-heavy
    else
      run_direct_ignored "$SELECTED_DRYRUN_DIR"
    fi
    MODE_SUMMARY="Ran broad ignored-file dry run"
    ;;
  direct-ignored-copy)
    if [[ "$INCLUDE_HEAVY" == true ]]; then
      run_direct_ignored "$SELECTED_FINAL_DIR" --include-heavy --copy
    else
      run_direct_ignored "$SELECTED_FINAL_DIR" --copy
    fi
    MODE_SUMMARY="Ran broad ignored-file copy"
    ;;
  selected-dry-run)
    run_selected "$SELECTED_DRYRUN_DIR"
    MODE_SUMMARY="Ran selected-pattern dry run"
    ;;
  selected-filtered-dry-run)
    if [[ ! -f "$EXCLUDE_LIST_PATH" ]]; then
      echo "ERROR: exclude list not found: $EXCLUDE_LIST_PATH" >&2
      exit 2
    fi
    run_selected "$SELECTED_FILTERED_DRYRUN_DIR" --exclude-list "$EXCLUDE_LIST_PATH"
    MODE_SUMMARY="Ran selected-pattern filtered dry run"
    ;;
  selected-copy)
    if [[ ! -f "$EXCLUDE_LIST_PATH" ]]; then
      echo "ERROR: exclude list not found: $EXCLUDE_LIST_PATH" >&2
      exit 2
    fi
    run_selected "$SELECTED_FINAL_DIR" --exclude-list "$EXCLUDE_LIST_PATH" --copy
    MODE_SUMMARY="Ran selected-pattern final copy"
    ;;
  stale-ignore-scan)
    # Reads the pattern/source map the default refresh already wrote, so this
    # costs no second repository walk and can be rerun on its own.
    STALE_IGNORE_SOURCES="$GITIGNORE_DIR/gitignore-pattern-sources.tsv"
    if [[ ! -f "$STALE_IGNORE_SOURCES" ]]; then
      echo "ERROR: pattern sources not found: $STALE_IGNORE_SOURCES" >&2
      echo "Run the default refresh first so the gitignore superset exists." >&2
      exit 2
    fi
    STALE_IGNORE_REPORT="$GITIGNORE_DIR/stale-ignore-entries.tsv"
    run_with_status "Stale ignore-entry scan" \
      python3 "$STALE_IGNORE_HELPER" \
        --sources-tsv "$STALE_IGNORE_SOURCES" \
        --out "$STALE_IGNORE_REPORT"
    OPEN_TARGET="$STALE_IGNORE_REPORT"
    MODE_SUMMARY="Scanned for stale single-file ignore entries"
    ;;
esac

echo "Repo backup: $MODE_SUMMARY"
if [[ "$MODE" == "default" ]]; then
  echo "Audit manifest: $MANIFEST_PATH"
  echo "Official pointer:   $REPO_AUDIT_DIR/official/pre-image.txt"
  echo "Latest audit report: $LATEST_AUDIT_REPORT"
fi
if [[ "$OPEN_AFTER" == true ]]; then
  if [[ -z "$OPEN_TARGET" || ! -e "$OPEN_TARGET" ]]; then
    echo "ERROR: primary output is not available to open: ${OPEN_TARGET:-<empty>}" >&2
    exit 1
  fi
  open "$OPEN_TARGET"
fi
